// Builds the static prototypes of issue #314 and their screenshots.
//
//   node docs/design/schermate-2026-09-28/genera.mjs            tokens, icons, screenshots and measures
//   node docs/design/schermate-2026-09-28/genera.mjs --no-shots  tokens and icons only
//
// Run it from the repository root after `npm ci` in app/: it reads the design tokens from
// app/src/renderer/index.css and the Tabler icons from app/node_modules, so the prototypes use the same values
// as the app. Screenshots use Playwright's Chromium; set CHROMIUM_PATH when Playwright's own build is missing.
import { createRequire } from "node:module";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const app = join(root, "app");
const protoDir = join(here, "prototipi");
const shotDir = join(here, "schermate");

// --- Tokens -------------------------------------------------------------------------------------------------

/** Splits a stylesheet into its top-level blocks: { prelude, body }. Comments are dropped. */
function topLevelBlocks(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks = [];
  let depth = 0;
  let start = 0;
  let preludeEnd = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === "{") {
      if (depth === 0) preludeEnd = i;
      depth++;
    } else if (ch === "}") {
      depth--;
      if (depth === 0) {
        blocks.push({ prelude: text.slice(start, preludeEnd).trim(), body: text.slice(preludeEnd + 1, i) });
        start = i + 1;
      }
    } else if (ch === ";" && depth === 0) {
      start = i + 1;
    }
  }
  return blocks;
}

// Rules copied as they are: theme tokens, the provider theme the prototypes use, and the shared components that
// are plain CSS in index.css (cta-row, seam, chat card, sash, agent identity).
const KEEP = [
  /^:root$/,
  /^:root\.dark$/,
  /^:root\[data-provider="codex"\]$/,
  /^:root\.dark\[data-provider="codex"\]$/,
  /^\.cta-row/,
  /^\.chat-card/,
  /^\.sash/,
  /^\.agent-identity$/,
  /^:root\.dark \.agent-identity$/,
  /^::selection$/,
];

async function buildTokens() {
  const css = await readFile(join(app, "src/renderer/index.css"), "utf8");
  const blocks = topLevelBlocks(css);
  const theme = blocks.find((b) => b.prelude === "@theme inline");
  // The @theme block maps Tailwind names to the tokens (text sizes, radii, colors); keep its custom properties.
  const themeVars = theme.body
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => /^--(text|color|radius|font)-[a-z0-9-]+:/.test(line));
  const kept = blocks.filter((b) => KEEP.some((re) => re.test(b.prelude)));
  const out = [
    "/* Generated by genera.mjs from app/src/renderer/index.css. Do not edit: run the script again. */",
    `:root {\n  ${themeVars.join("\n  ")}\n}`,
    ...kept.map((b) => `${b.prelude} {${b.body}}`),
  ].join("\n\n");
  await writeFile(join(protoDir, "tokens.css"), `${out}\n`);
  return kept.length;
}

// --- Icons --------------------------------------------------------------------------------------------------

async function buildIcons() {
  // Every quoted name in the prototypes' scripts that is an outline icon of the Tabler set the app uses.
  // The package that @tabler/icons-react draws from; its exports do not include package.json.
  const tablerDir = join(app, "node_modules/@tabler/icons");
  const version = JSON.parse(await readFile(join(tablerDir, "package.json"), "utf8")).version;
  const available = new Set((await readdir(join(tablerDir, "icons/outline"))).map((f) => f.replace(/\.svg$/, "")));
  const names = new Set();
  for (const file of await readdir(protoDir)) {
    if (!file.endsWith(".js") || file === "icons.js") continue;
    const text = await readFile(join(protoDir, file), "utf8");
    for (const m of text.matchAll(/"([a-z0-9-]+)"/g)) if (available.has(m[1])) names.add(m[1]);
  }
  const icons = {};
  for (const name of [...names].sort()) {
    const svg = await readFile(join(tablerDir, "icons/outline", `${name}.svg`), "utf8");
    icons[name] = [...svg.matchAll(/<path [^>]*d="([^"]+)"/g)]
      .map((m) => m[1])
      .filter((d) => d !== "M0 0h24v24H0z");
  }
  const body = `// Generated by genera.mjs from @tabler/icons ${version} (MIT), the icon set of app/src/renderer.\nwindow.ICONS = ${JSON.stringify(icons, null, 0)};\n`;
  await writeFile(join(protoDir, "icons.js"), body);
  return names.size;
}

// --- Screenshots and measures -------------------------------------------------------------------------------

const ALTERNATIVES = ["a", "b", "c"];
const STATES = ["principale", "aspetta", "squadre", "specialista", "lavoro", "regole", "memoria", "panoramica", "impostazioni"];
const THEMES = ["chiaro", "scuro"];
const SIZES = {
  base: { width: 1280, height: 800 },
  // The audit's 1280x800 window at 120% zoom.
  zoom: { width: 1066, height: 666 },
  larga: { width: 1680, height: 1050 },
};

async function launchBrowser() {
  const require = createRequire(join(app, "package.json"));
  const { chromium } = require("playwright");
  try {
    return await chromium.launch();
  } catch (error) {
    if (!process.env.CHROMIUM_PATH) throw error;
    return chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
  }
}

/** What the person sees at once: the room left to the conversation and the buttons in view. */
function measure() {
  const inView = (el) => {
    const r = el.getBoundingClientRect();
    if (r.width === 0 || r.height === 0) return false;
    const style = getComputedStyle(el);
    if (style.visibility === "hidden" || style.display === "none") return false;
    return r.bottom > 0 && r.right > 0 && r.top < innerHeight && r.left < innerWidth;
  };
  const conversation = document.querySelector("[data-misura='conversazione']");
  const rect = conversation && inView(conversation) ? conversation.getBoundingClientRect() : null;
  const buttons = [...document.querySelectorAll("button, [role='tab']")].filter(inView);
  const kind = (b) => {
    const hasIcon = !!b.querySelector("svg");
    const hasText = b.textContent.trim().length > 0 && !b.classList.contains("badge-only");
    return hasIcon && hasText ? "iconaTesto" : hasIcon ? "icona" : "testo";
  };
  const count = { testo: 0, iconaTesto: 0, icona: 0 };
  for (const b of buttons) count[kind(b)]++;
  return {
    conversazione: rect ? { altezza: Math.round(rect.height), larghezza: Math.round(rect.width) } : null,
    pulsanti: buttons.length,
    ...count,
    pieni: buttons.filter((b) => b.dataset.variant === "default").length,
    urgenti: document.querySelectorAll("[data-urgente]").length,
  };
}

async function shoot() {
  await rm(shotDir, { recursive: true, force: true });
  await mkdir(shotDir, { recursive: true });
  const browser = await launchBrowser();
  const measures = {};
  for (const alt of ALTERNATIVES) {
    measures[alt] = {};
    for (const [sizeName, size] of Object.entries(SIZES)) {
      const page = await browser.newPage({ viewport: size, deviceScaleFactor: 1 });
      for (const theme of THEMES) {
        for (const state of STATES) {
          const url = `${pathToFileURL(join(protoDir, `${alt}.html`)).href}?vista=${state}&tema=${theme}&scatto=1`;
          await page.goto(url);
          await page.waitForFunction(() => document.documentElement.dataset.pronto === "1");
          const errors = await page.evaluate(() => window.PROTO_ERRORS ?? []);
          if (errors.length) throw new Error(`${alt} ${state}: ${errors.join("; ")}`);
          if (theme === "chiaro") (measures[alt][state] ??= {})[sizeName] = await page.evaluate(measure);
          // Screenshots: every state at 1280x800, the main window and two views also wider.
          const wide = sizeName === "larga" && ["principale", "squadre", "specialista", "lavoro"].includes(state);
          if (sizeName === "base" || wide) {
            const name = `${alt}-${state}-${theme}${sizeName === "larga" ? "-larga" : ""}.png`;
            await page.screenshot({ path: join(shotDir, name) });
          }
        }
      }
      await page.close();
    }
  }
  await browser.close();
  await writeFile(join(here, "misure.json"), `${JSON.stringify(measures, null, 2)}\n`);
  return measures;
}

const tokens = await buildTokens();
const icons = await buildIcons();
console.log(`tokens.css: ${tokens} rules; icons.js: ${icons} icons`);
if (!process.argv.includes("--no-shots")) {
  const measures = await shoot();
  for (const alt of ALTERNATIVES) {
    const m = measures[alt].principale;
    console.log(alt, "principale", JSON.stringify(m.base), "zoom", JSON.stringify(m.zoom?.conversazione));
  }
}
